#!/usr/bin/env python3
"""Writes the big-200-ops OpenAPI fixture: 200 operations, 20 tags, 40 schemas.

Deterministic: rerunning rewrites identical bytes. Optional fields are chosen by hashing a fixed
key with sha256, not by the random module, so output does not depend on the Python version.
Standard library only. Usage: python3 scripts/gen-big-spec.py
"""

import hashlib
import pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = (
    REPO / "backend/generators/core/src/testFixtures/resources/golden-inputs/big-200-ops.yaml"
)

# Plural path segment and singular schema name for each of the 20 resources.
RESOURCES = [
    tuple(pair.split(":"))
    for pair in """
    accounts:Account invoices:Invoice orders:Order products:Product customers:Customer
    shipments:Shipment payments:Payment refunds:Refund carts:Cart reviews:Review
    categories:Category inventory-items:InventoryItem warehouses:Warehouse
    suppliers:Supplier teams:Team projects:Project tasks:Task comments:Comment
    notifications:Notification reports:Report
    """.split()
]

EXTRA_FIELDS = [
    "amount: {type: number, format: double}",
    "rating: {type: integer, minimum: 1, maximum: 5}",
    "email: {type: string, format: email}",
    "active: {type: boolean}",
    "notes: {type: string, nullable: true}",
]

ID = "{name: id, in: path, required: true, schema: {type: integer, format: int64}}"
CURSOR = "{name: cursor, in: query, schema: {type: string}}"
LIMIT = "{name: limit, in: query, schema: {type: integer, minimum: 1, maximum: 100}}"
FORMAT = "{name: format, in: query, schema: {type: string, enum: [csv, json]}}"
STATUS = "{type: string, enum: [active, archived]}"

HEADER = """\
# Generated by scripts/gen-big-spec.py. Do not edit by hand.
openapi: 3.0.3
info:
  title: Big 200 Operations
  version: 1.0.0
security:
  - bearerAuth: []
tags:"""

FOOTER = """\
components:
  securitySchemes:
    bearerAuth:
      type: http
      scheme: bearer
  schemas:"""

SCHEMAS = """\
    @s@:
      type: object
      required: [id, name]
      properties:
        id: {type: integer, format: int64}
        name: {type: string}
        status: @status@
        createdAt: {type: string, format: date-time}
        @extra@
    @s@Input:
      type: object
      required: [name]
      properties:
        name: {type: string}
        status: @status@"""


def ref(name):
    return "{$ref: '#/components/schemas/" + name + "'}"


def pascal(plural):
    return "".join(part.capitalize() for part in plural.split("-"))


def pick(options, key):
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return options[int.from_bytes(digest[:8], "big") % len(options)]


def operation(
    method, op_id, tag, params=(), body=None, status="200", schema=None, media="application/json"
):
    lines = [f"    {method}:", f"      operationId: {op_id}", f"      tags: [{tag}]"]
    if params:
        lines += ["      parameters:"] + [f"        - {p}" for p in params]
    if body:
        lines += [
            "      requestBody:",
            "        required: true",
            "        content:",
            "          application/json:",
            "            schema: " + ref(body),
        ]
    lines += ["      responses:", f"        '{status}':", "          description: ok"]
    if schema:
        lines += ["          content:", f"            {media}:", f"              schema: {schema}"]
    return lines


def path(template, operations, params=()):
    lines = ["  '" + template + "':"]
    if params:
        lines += ["    parameters:"] + [f"      - {p}" for p in params]
    for op in operations:
        lines += op
    return lines


def resource_paths(plural, singular):
    tag, s, item = plural, singular, "/" + plural + "/{id}"
    one = ref(s)
    many = "{type: array, items: " + one + "}"
    return [
        path(
            "/" + plural,
            [
                operation("get", "list" + pascal(plural), tag, [CURSOR, LIMIT], schema=many),
                operation("post", "create" + s, tag, body=s + "Input", status="201", schema=one),
            ],
        ),
        path(
            item,
            [
                operation("get", "get" + s, tag, schema=one),
                operation("put", "replace" + s, tag, body=s + "Input", schema=one),
                operation("patch", "update" + s, tag, body=s + "Input", schema=one),
                operation("delete", "delete" + s, tag, status="204"),
            ],
            params=[ID],
        ),
        path(item + "/archive", [operation("post", "archive" + s, tag, schema=one)], [ID]),
        path(item + "/restore", [operation("post", "restore" + s, tag, schema=one)], [ID]),
        path(
            item + "/history",
            [operation("get", "get" + s + "History", tag, [LIMIT], schema=many)],
            [ID],
        ),
        path(
            "/" + plural + "/export",
            [
                operation(
                    "get",
                    "export" + pascal(plural),
                    tag,
                    [FORMAT],
                    schema="{type: string}",
                    media="text/csv",
                )
            ],
        ),
    ]


def schema_block(singular):
    return (
        SCHEMAS.replace("@s@", singular)
        .replace("@status@", STATUS)
        .replace("@extra@", pick(EXTRA_FIELDS, singular))
    )


def document():
    lines = [HEADER]
    lines += ["  - name: " + plural for plural, _ in RESOURCES]
    lines.append("paths:")
    for plural, singular in RESOURCES:
        for block in resource_paths(plural, singular):
            lines += block
    lines.append(FOOTER)
    lines += [schema_block(singular) for _, singular in RESOURCES]
    return "\n".join(lines) + "\n"


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(document(), encoding="utf-8")
    print("wrote " + str(OUTPUT.relative_to(REPO)))


if __name__ == "__main__":
    main()
